#!/usr/bin/env node
// Builds public/preview-runtime/: React + ReactDOM, the JSX compiler (Sucrase)
// and Tailwind for React previews, so a component that only uses React works
// offline. Extra npm packages a component imports (lucide-react, recharts, ...)
// still come from esm.sh, with react and react-dom left external so they bind
// to this one React.
//
// Why classic scripts and not ES modules: previews run in sandboxed srcdoc
// frames (opaque origin), and Chromium refuses any request from such a frame
// to localhost. So the app page fetches these files from its own server and
// inlines them into the preview document; the frame's import map points
// `react` etc. at small data: modules that re-export the globals set here
// (`__piPreviewRuntime`, `__piSucrase`). manifest.json lists those exports.
//
// The output is committed. Run `npm run preview-runtime` after bumping react,
// react-dom, sucrase, @tailwindcss/browser or esbuild; scripts/preview-runtime
// .test.mjs fails until the files match package-lock.json again.

import { createRequire } from "node:module";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

process.env.NODE_ENV = "production";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "preview-runtime");
const require = createRequire(join(root, "package.json"));
const { build } = require("esbuild");

const version = (name) => require(`${name}/package.json`).version;

// One bundle holds every React module, so the runtime has a single copy of
// React however a component (or a package from esm.sh) imports it.
const REACT_MODULES = {
  react: "React",
  "react/jsx-runtime": "JsxRuntime",
  "react-dom": "ReactDom",
  "react-dom/client": "ReactDomClient",
};

const banner = (text) => `/* ${text} — generated by scripts/build-preview-runtime.mjs; do not edit. */`;

async function bundle(entryContents, outfile, label) {
  await build({
    stdin: { contents: entryContents, resolveDir: root, loader: "js" },
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2020",
    minify: true,
    legalComments: "eof",
    define: { "process.env.NODE_ENV": '"production"' },
    banner: { js: banner(label) },
    outfile,
    logLevel: "error",
  });
}

async function main() {
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  const reactVersion = version("react");
  const imports = Object.entries(REACT_MODULES)
    .map(([specifier, name]) => `import * as ${name} from ${JSON.stringify(specifier)};`)
    .join("\n");
  await bundle(
    `${imports}\nglobalThis.__piPreviewRuntime = { ${Object.values(REACT_MODULES).join(", ")} };`,
    join(outDir, "react.js"),
    `react ${reactVersion}, react-dom ${version("react-dom")}`,
  );

  await bundle(
    'import { transform } from "sucrase";\nglobalThis.__piSucrase = { transform };',
    join(outDir, "sucrase.js"),
    `sucrase ${version("sucrase")}`,
  );

  await copyFile(require.resolve("@tailwindcss/browser"), join(outDir, "tailwind.js"));

  const files = ["react.js", "sucrase.js", "tailwind.js"];
  const manifest = {
    note: "Generated by scripts/build-preview-runtime.mjs. Versions must match package-lock.json.",
    versions: {
      react: reactVersion,
      "react-dom": version("react-dom"),
      sucrase: version("sucrase"),
      "@tailwindcss/browser": version("@tailwindcss/browser"),
    },
    files: {},
    // Named exports of each module, keyed by specifier, with the global they live on.
    modules: Object.fromEntries(Object.entries(REACT_MODULES).map(([specifier, name]) => [
      specifier,
      { global: name, exports: Object.keys(require(specifier)).filter((key) => key !== "default").sort() },
    ])),
  };
  for (const file of files) {
    manifest.files[file] = (await readFile(join(outDir, file))).length;
  }
  await writeFile(join(outDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

  const total = Object.values(manifest.files).reduce((sum, size) => sum + size, 0);
  console.log(`preview runtime: ${files.length} files, ${(total / 1024).toFixed(0)} KiB in public/preview-runtime`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
